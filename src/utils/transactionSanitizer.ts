import { Transaction, OnChainLedgerEntry } from '../types';

/**
 * Known simulated, test, or non-existent transaction hashes created during development/testing
 */
export const KNOWN_SIMULATED_HASHES = new Set<string>([
  '0x7479fa28254dd5cfe710253ebef6e817d5257f932c76a66889038cc0ea27ee4f'.toLowerCase(),
]);

/**
 * Validates if an on-chain transaction hash is a legitimate 66-character EVM hexadecimal hash (Base L2)
 */
export function isRealTxHash(hash?: string | null): boolean {
  if (!hash || typeof hash !== 'string') return false;
  const clean = hash.trim().toLowerCase();
  if (KNOWN_SIMULATED_HASHES.has(clean)) return false;
  return /^0x[a-f0-9]{64}$/.test(clean);
}

/**
 * Evaluates whether a transaction is a simulation, placeholder, or non-real record.
 */
export function isSimulatedTransaction(tx: Transaction): boolean {
  if (!tx) return true;

  // 1. Check known simulated hashes immediately
  if (tx.txHash && KNOWN_SIMULATED_HASHES.has(tx.txHash.trim().toLowerCase())) {
    return true;
  }

  // 2. Synthetic balance reconciliation deposit generated by earlier code versions
  if (tx.id?.startsWith('tx-onchain-deposit-')) {
    return true;
  }

  // 3. Legacy demo or test IDs
  const DEMO_TX_IDS = new Set(['tx_1', 'tx_2', 'tx_3', 'tx_4', 'tx_5', 'tx_6', 'tx_7']);
  if (DEMO_TX_IDS.has(tx.id)) {
    return true;
  }
  if (
    tx.id?.startsWith('tx_demo_') ||
    tx.id?.startsWith('tx_test_') ||
    tx.id?.startsWith('tx_mock_') ||
    tx.id?.startsWith('tx_simul_')
  ) {
    return true;
  }

  // 4. Transactions claiming to be On-Chain, but lacking a real Base blockchain transaction hash
  if (tx.isOnChain) {
    if (!tx.txHash || !isRealTxHash(tx.txHash)) {
      return true;
    }
  }

  // 5. Any transaction with a synthetic/fake hash (such as deposit-...)
  if (tx.txHash && !isRealTxHash(tx.txHash)) {
    return true;
  }

  // 6. Explicit simulation text or synthetic deposits without a verified on-chain hash
  const desc = (tx.description || '').toLowerCase();
  const notes = (tx.notes || '').toLowerCase();

  if (
    (desc.includes('depósito em carteira') || notes.includes('rede base (depósito)')) &&
    (!tx.txHash || !isRealTxHash(tx.txHash))
  ) {
    return true;
  }

  if (
    /simula[çc][ãa]o|simulad[oa]|transa[çc][ãa]o teste|\bmock\b|placeholder/i.test(desc) ||
    /simula[çc][ãa]o|simulad[oa]|transa[çc][ãa]o teste|\bmock\b/i.test(notes)
  ) {
    // If it has a real verified on-chain BaseScan hash, it is a real blockchain transfer
    if (!tx.txHash || !isRealTxHash(tx.txHash)) {
      return true;
    }
  }

  return false;
}

/**
 * Checks if a transaction is a genuine, verified payment/receipt
 */
export function isRealTransaction(tx: Transaction): boolean {
  return !isSimulatedTransaction(tx);
}

/**
 * Evaluates whether an on-chain ledger entry is a simulation or placeholder
 */
export function isSimulatedLedgerEntry(entry: OnChainLedgerEntry): boolean {
  if (!entry) return true;

  // Real Base on-chain ledger entries MUST have a real 66-character hex hash
  if (!entry.txHash || !isRealTxHash(entry.txHash)) {
    return true;
  }

  // Placeholder deposit address
  const fromAddr = (entry.fromAddress || '').toLowerCase();
  if (fromAddr.includes('rede base (depósito)') || fromAddr.includes('depósito')) {
    return true;
  }

  const label = (entry.originalLabel || '').toLowerCase();
  if (
    /dep[oó]sito em carteira|simula[çc][ãa]o|simulad[oa]|\bmock\b/i.test(label) &&
    !isRealTxHash(entry.txHash)
  ) {
    return true;
  }

  return false;
}

/**
 * Checks if an on-chain ledger entry is genuine
 */
export function isRealLedgerEntry(entry: OnChainLedgerEntry): boolean {
  return !isSimulatedLedgerEntry(entry);
}

/**
 * Purges all simulated transactions and returns only real payments/receipts
 */
export function sanitizeTransactions(transactions: Transaction[]): Transaction[] {
  if (!Array.isArray(transactions)) return [];
  return transactions.filter(isRealTransaction);
}

/**
 * Purges all simulated ledger entries and returns only verified Base blockchain entries
 */
export function sanitizeLedgerEntries(entries: OnChainLedgerEntry[]): OnChainLedgerEntry[] {
  if (!Array.isArray(entries)) return [];
  return entries.filter(isRealLedgerEntry);
}
